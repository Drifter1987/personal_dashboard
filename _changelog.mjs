#!/usr/bin/env node
/* Release notes for the repository.

     node _changelog.mjs          write CHANGELOG.md from the page's own CHANGELOG array
     node _changelog.mjs --check  exit 1 if CHANGELOG.md is out of date (no writes)
     node _changelog.mjs --help

   The page already carries every release in its `CHANGELOG` array, which is what the in-app
   modal renders in both languages. This script turns that array into CHANGELOG.md instead of
   keeping a second hand-written history that would drift from it; the array stays the single
   source of truth, so a release is: bump the version, add the entry, run this.
*/
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = dirname(fileURLToPath(import.meta.url));
const PAGE = "index.html";
const OUT = "CHANGELOG.md";

const HELP = `Release notes from the page's own changelog array.

  node _changelog.mjs          write ${OUT}
  node _changelog.mjs --check  exit 1 if ${OUT} is out of date (writes nothing)`;

const argv = process.argv.slice(2);
if (argv.includes("--help") || argv.includes("-h")) {
  console.log(HELP);
  process.exit(0);
}
const unknown = argv.filter((a) => a !== "--check");
if (unknown.length) {
  console.error("_changelog.mjs: unknown flag(s) " + unknown.join(" ") + "\n\n" + HELP);
  process.exit(2);
}
const CHECK = argv.includes("--check");

const src = readFileSync(join(ROOT, PAGE), "utf8");
const block = (src.match(/const CHANGELOG = \[[\s\S]*?\n\];/) || [])[0];
if (!block) {
  console.error("_changelog.mjs: no CHANGELOG array found in " + PAGE + " - nothing written.");
  process.exit(1);
}
let entries;
try {
  entries = new Function(block + "\nreturn CHANGELOG;")();
} catch (e) {
  console.error("_changelog.mjs: the CHANGELOG array in " + PAGE + " does not parse: " + e.message);
  process.exit(1);
}
if (!Array.isArray(entries) || !entries.length) {
  console.error("_changelog.mjs: the CHANGELOG array is empty - nothing written.");
  process.exit(1);
}
const bad = entries.filter((e) => !e || !e.v || !e.d || typeof e.en !== "string" || !e.en.trim());
if (bad.length) {
  console.error("_changelog.mjs: " + bad.length + " entr" + (bad.length === 1 ? "y is" : "ies are")
    + " missing version, date or English text (Arabic is checked by the harness, not here).");
  process.exit(1);
}

const running = (src.match(/VERSION: "([0-9.]+)"/) || [])[1] || "unknown";
const newest = entries[0].v;
const version = (v) => v.split(".").map((n) => Number(n));

const file = "# Changelog\n\n"
  + "Release notes for the Home Dashboard, newest first. Generated from the `CHANGELOG` array in\n"
  + "[" + PAGE + "](" + PAGE + ") — the same entries the in-app Changelog modal shows in English and\n"
  + "Arabic — by `node _changelog.mjs`. Do not edit this file by hand: edit the array and regenerate.\n\n"
  + "The running page is **v" + running + "**; the newest entry below is **v" + newest + "**"
  + (running === newest ? ".\n" : " — the page and its history disagree, which the deploy gate blocks.\n")
  + "\n"
  + entries.map((e) => "## " + e.v + " — " + e.d + "\n\n" + e.en.trim() + "\n").join("\n")
  + "\n---\n\n"
  + entries.length + " releases, v" + entries[entries.length - 1].v + " (" + entries[entries.length - 1].d
  + ") through v" + newest + " (" + entries[0].d + ").\n";

/* the array is written newest-first; a file that says otherwise is worse than no file */
for (let i = 1; i < entries.length; i++) {
  const a = version(entries[i - 1].v), b = version(entries[i].v);
  const cmp = a[0] - b[0] || a[1] - b[1] || (a[2] || 0) - (b[2] || 0);
  if (cmp < 0) {
    console.error("_changelog.mjs: " + entries[i].v + " is newer than " + entries[i - 1].v
      + " but sits below it - fix the array order first.");
    process.exit(1);
  }
}

const path = join(ROOT, OUT);
const current = existsSync(path) ? readFileSync(path, "utf8") : null;

if (CHECK) {
  if (current === file) {
    console.log("CHANGELOG OK: " + OUT + " matches the " + entries.length + " entries in " + PAGE
      + " (newest v" + newest + ").");
    process.exit(0);
  }
  console.log("CHANGELOG STALE: " + OUT + " is " + (current === null ? "missing" : "out of date")
    + " - run node _changelog.mjs.");
  process.exit(1);
}

if (current === file) {
  console.log("CHANGELOG OK: " + OUT + " already matches the " + entries.length + " entries in "
    + PAGE + " - nothing written.");
  console.log("Newest entry: v" + newest + " (" + entries[0].d + "); running page: v" + running + ".");
  process.exit(0);
}
writeFileSync(path, file);
console.log((current === null ? "wrote " : "updated ") + OUT + " from " + entries.length + " entries in "
  + PAGE + " (" + file.length + " bytes).");
console.log("Newest entry: v" + newest + " (" + entries[0].d + "); running page: v" + running + ".");
